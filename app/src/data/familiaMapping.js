/**
 * Normaliza un valor de familia a categoría
 */
export function normalizarFamilia(familia) {
  if (!familia) return null;
  
  // Limpieza básica
  const limpio = familia.toUpperCase().trim();
  
  // Buscar coincidencia exacta
  if (FAMILIA_A_CATEGORIA[limpio]) {
    return FAMILIA_A_CATEGORIA[limpio];
  }
  
  // Buscar coincidencia parcial (si el valor contiene alguna clave)
  for (const [key, value] of Object.entries(FAMILIA_A_CATEGORIA)) {
    if (limpio.includes(key) || key.includes(limpio.slice(0, 20))) {
      return value;
    }
  }
  
  // Si no hay coincidencia, devolver null
  return null;
}

